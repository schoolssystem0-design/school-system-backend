-- =====================================================================
-- V002 Phase 1: platform login history, roles & permissions, account management,
-- school profile & files, academic years & calendar, settings, academic structure.
-- Every school-owned table: school_id NOT NULL, RLS policy, school_id in unique + foreign keys.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Platform (super admin) login history: platform-level, no RLS
-- ---------------------------------------------------------------------
CREATE TABLE platform_login_event (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    platform_user_id  BIGINT       REFERENCES platform_user (id),
    email             VARCHAR(254) NOT NULL,
    result            VARCHAR(20)  NOT NULL CHECK (result IN ('SUCCESS', 'INVALID', 'BLOCKED', 'TOTP_INVALID')),
    ip                VARCHAR(64),
    user_agent        VARCHAR(400),
    at                TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX platform_login_event_at_idx ON platform_login_event (at DESC);

ALTER TABLE platform_user ADD COLUMN failed_attempts INT NOT NULL DEFAULT 0;
ALTER TABLE platform_user ADD COLUMN locked_until TIMESTAMPTZ;
ALTER TABLE platform_user ADD COLUMN last_login_at TIMESTAMPTZ;

ALTER TABLE school ADD COLUMN suspended_reason VARCHAR(500);
-- The platform reserves a new school's ID (nextval) before creating it, so the school row, its profile, roles and
-- main administrator are inserted in ONE transaction that already runs as the new school (RLS context is fixed
-- when the connection is taken).
ALTER TABLE school ALTER COLUMN id SET GENERATED BY DEFAULT;

-- ---------------------------------------------------------------------
-- School users: contact details, data scope, optional sign-in TOTP
-- ---------------------------------------------------------------------
ALTER TABLE app_user ADD COLUMN email       VARCHAR(254);
ALTER TABLE app_user ADD COLUMN phone       VARCHAR(30);
ALTER TABLE app_user ADD COLUMN data_scope  VARCHAR(30) NOT NULL DEFAULT 'ALL'
    CHECK (data_scope IN ('ALL', 'ASSIGNED_CLASSES', 'SELF'));
ALTER TABLE app_user ADD COLUMN is_main_admin BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app_user ADD COLUMN password_changed_at TIMESTAMPTZ;
CREATE UNIQUE INDEX app_user_one_main_admin_uq ON app_user (school_id) WHERE is_main_admin;

ALTER TABLE login_event ADD COLUMN new_location BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE login_event ADD COLUMN ip_prefix VARCHAR(64);
CREATE INDEX login_event_user_prefix_idx ON login_event (school_id, user_id, ip_prefix) WHERE result = 'SUCCESS';

-- ---------------------------------------------------------------------
-- Roles and permissions (FR 1.7, 2.5)
-- ---------------------------------------------------------------------
CREATE TABLE role (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES school (id),
    code              VARCHAR(40)  NOT NULL,
    name              VARCHAR(100) NOT NULL,
    description       VARCHAR(300),
    system_role       BOOLEAN      NOT NULL DEFAULT FALSE,
    template_version  INT          NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT role_school_id_uq UNIQUE (school_id, id),
    CONSTRAINT role_code_uq UNIQUE (school_id, code),
    CONSTRAINT role_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]{1,39}$')
);

CREATE TABLE role_permission (
    school_id   BIGINT       NOT NULL REFERENCES school (id),
    role_id     BIGINT       NOT NULL,
    permission  VARCHAR(80)  NOT NULL,
    PRIMARY KEY (role_id, permission),
    CONSTRAINT role_permission_role_fk FOREIGN KEY (school_id, role_id) REFERENCES role (school_id, id) ON DELETE CASCADE
);

CREATE TABLE user_role (
    school_id  BIGINT NOT NULL REFERENCES school (id),
    user_id    BIGINT NOT NULL,
    role_id    BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT user_role_user_fk FOREIGN KEY (school_id, user_id) REFERENCES app_user (school_id, id),
    CONSTRAINT user_role_role_fk FOREIGN KEY (school_id, role_id) REFERENCES role (school_id, id)
);
CREATE INDEX user_role_role_idx ON user_role (school_id, role_id);

-- Account activation / deactivation history (FR 2.4)
CREATE TABLE account_status_change (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id    BIGINT       NOT NULL REFERENCES school (id),
    user_id      BIGINT       NOT NULL,
    from_status  VARCHAR(20)  NOT NULL,
    to_status    VARCHAR(20)  NOT NULL,
    reason       VARCHAR(500) NOT NULL,
    actor_type   VARCHAR(20)  NOT NULL CHECK (actor_type IN ('USER', 'PLATFORM', 'SYSTEM')),
    actor_id     BIGINT,
    at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT account_status_change_user_fk FOREIGN KEY (school_id, user_id) REFERENCES app_user (school_id, id)
);

-- One-time tokens: account setup links and password resets (FR 2.3). Only a SHA-256 hash is stored.
CREATE TABLE password_token (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id      BIGINT       NOT NULL REFERENCES school (id),
    user_id        BIGINT       NOT NULL,
    purpose        VARCHAR(20)  NOT NULL CHECK (purpose IN ('SETUP', 'RESET')),
    token_hash     VARCHAR(64)  NOT NULL,
    channel        VARCHAR(20)  NOT NULL CHECK (channel IN ('EMAIL', 'SMS', 'LINK')),
    expires_at     TIMESTAMPTZ  NOT NULL,
    used_at        TIMESTAMPTZ,
    created_by_type VARCHAR(20) NOT NULL CHECK (created_by_type IN ('USER', 'PLATFORM', 'SYSTEM')),
    created_by_id  BIGINT,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT password_token_user_fk FOREIGN KEY (school_id, user_id) REFERENCES app_user (school_id, id)
);
CREATE UNIQUE INDEX password_token_hash_uq ON password_token (token_hash);

-- ---------------------------------------------------------------------
-- Files (photos, logos, documents) stored in R2; metadata here
-- ---------------------------------------------------------------------
CREATE TABLE stored_file (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id      BIGINT        NOT NULL REFERENCES school (id),
    storage_key    VARCHAR(300)  NOT NULL,
    purpose        VARCHAR(40)   NOT NULL,
    original_name  VARCHAR(255)  NOT NULL,
    content_type   VARCHAR(100)  NOT NULL,
    size_bytes     BIGINT        NOT NULL CHECK (size_bytes > 0),
    sha256         VARCHAR(64)   NOT NULL,
    created_by_type VARCHAR(20)  NOT NULL,
    created_by_id  BIGINT,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT stored_file_school_id_uq UNIQUE (school_id, id)
);
CREATE UNIQUE INDEX stored_file_key_uq ON stored_file (storage_key);

-- ---------------------------------------------------------------------
-- School profile and document identity (FR 1.1)
-- ---------------------------------------------------------------------
CREATE TABLE school_profile (
    school_id          BIGINT       PRIMARY KEY REFERENCES school (id),
    name               VARCHAR(200) NOT NULL,
    campus_name        VARCHAR(200),
    address            VARCHAR(500),
    phone_primary      VARCHAR(30),
    phone_secondary    VARCHAR(30),
    email              VARCHAR(254),
    head_name          VARCHAR(200),
    head_title         VARCHAR(100),
    logo_file_id       BIGINT,
    letterhead_file_id BIGINT,
    stamp_file_id      BIGINT,
    signatures         JSONB        NOT NULL DEFAULT '[]'::jsonb,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version            BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT school_profile_logo_fk FOREIGN KEY (school_id, logo_file_id) REFERENCES stored_file (school_id, id),
    CONSTRAINT school_profile_letterhead_fk FOREIGN KEY (school_id, letterhead_file_id) REFERENCES stored_file (school_id, id),
    CONSTRAINT school_profile_stamp_fk FOREIGN KEY (school_id, stamp_file_id) REFERENCES stored_file (school_id, id)
);

-- ---------------------------------------------------------------------
-- Academic years, working week, holidays (FR 1.2, 1.4, 9.1)
-- ---------------------------------------------------------------------
CREATE TABLE academic_year (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id   BIGINT       NOT NULL REFERENCES school (id),
    name        VARCHAR(20)  NOT NULL,
    start_date  DATE         NOT NULL,
    end_date    DATE         NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'UPCOMING' CHECK (status IN ('UPCOMING', 'CURRENT', 'CLOSED')),
    opened_at   TIMESTAMPTZ,
    closed_at   TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT academic_year_school_id_uq UNIQUE (school_id, id),
    CONSTRAINT academic_year_name_uq UNIQUE (school_id, name),
    CONSTRAINT academic_year_dates CHECK (start_date < end_date)
);
CREATE UNIQUE INDEX academic_year_one_current_uq ON academic_year (school_id) WHERE status = 'CURRENT';

CREATE TABLE working_day (
    school_id         BIGINT      NOT NULL REFERENCES school (id),
    academic_year_id  BIGINT      NOT NULL,
    weekday           SMALLINT    NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    day_type          VARCHAR(10) NOT NULL CHECK (day_type IN ('FULL', 'HALF', 'OFF')),
    PRIMARY KEY (academic_year_id, weekday),
    CONSTRAINT working_day_year_fk FOREIGN KEY (school_id, academic_year_id) REFERENCES academic_year (school_id, id)
);

CREATE TABLE calendar_day_off (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id         BIGINT       NOT NULL REFERENCES school (id),
    academic_year_id  BIGINT       NOT NULL,
    date_from         DATE         NOT NULL,
    date_to           DATE         NOT NULL,
    title             VARCHAR(200) NOT NULL,
    type              VARCHAR(20)  NOT NULL CHECK (type IN ('HOLIDAY', 'VACATION')),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT calendar_day_off_year_fk FOREIGN KEY (school_id, academic_year_id) REFERENCES academic_year (school_id, id),
    CONSTRAINT calendar_day_off_dates CHECK (date_from <= date_to)
);
CREATE INDEX calendar_day_off_year_idx ON calendar_day_off (school_id, academic_year_id, date_from);

-- ---------------------------------------------------------------------
-- Settings (FR 12): append-only history; the latest row per key is the current value
-- ---------------------------------------------------------------------
CREATE TABLE setting_value (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id        BIGINT       NOT NULL REFERENCES school (id),
    setting_key      VARCHAR(80)  NOT NULL,
    value            JSONB        NOT NULL,
    reason           VARCHAR(500) NOT NULL,
    changed_by_type  VARCHAR(20)  NOT NULL CHECK (changed_by_type IN ('USER', 'PLATFORM', 'SYSTEM')),
    changed_by_id    BIGINT,
    changed_by_name  VARCHAR(200),
    changed_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX setting_value_key_idx ON setting_value (school_id, setting_key, id DESC);

-- ---------------------------------------------------------------------
-- Academic structure (FR 9)
-- ---------------------------------------------------------------------
CREATE TABLE school_class (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id      BIGINT       NOT NULL REFERENCES school (id),
    name           VARCHAR(60)  NOT NULL,
    short_name     VARCHAR(20)  NOT NULL,
    display_order  INT          NOT NULL,
    grading_mode   VARCHAR(10)  NOT NULL DEFAULT 'MARKS' CHECK (grading_mode IN ('MARKS', 'GRADES')),
    status         VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT school_class_school_id_uq UNIQUE (school_id, id)
);
CREATE UNIQUE INDEX school_class_name_uq ON school_class (school_id, lower(name));

CREATE TABLE section (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id   BIGINT       NOT NULL REFERENCES school (id),
    class_id    BIGINT       NOT NULL,
    name        VARCHAR(30)  NOT NULL,
    status      VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT section_school_id_uq UNIQUE (school_id, id),
    CONSTRAINT section_class_fk FOREIGN KEY (school_id, class_id) REFERENCES school_class (school_id, id)
);
CREATE UNIQUE INDEX section_name_uq ON section (school_id, class_id, lower(name));

CREATE TABLE subject (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id   BIGINT       NOT NULL REFERENCES school (id),
    name        VARCHAR(80)  NOT NULL,
    short_name  VARCHAR(20)  NOT NULL,
    status      VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT subject_school_id_uq UNIQUE (school_id, id)
);
CREATE UNIQUE INDEX subject_name_uq ON subject (school_id, lower(name));

CREATE TABLE class_subject (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id         BIGINT        NOT NULL REFERENCES school (id),
    academic_year_id  BIGINT        NOT NULL,
    class_id          BIGINT        NOT NULL,
    subject_id        BIGINT        NOT NULL,
    max_marks         NUMERIC(6, 2) NOT NULL CHECK (max_marks > 0),
    passing_marks     NUMERIC(6, 2),
    display_order     INT           NOT NULL,
    status            VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT class_subject_school_id_uq UNIQUE (school_id, id),
    CONSTRAINT class_subject_uq UNIQUE (school_id, academic_year_id, class_id, subject_id),
    CONSTRAINT class_subject_year_fk FOREIGN KEY (school_id, academic_year_id) REFERENCES academic_year (school_id, id),
    CONSTRAINT class_subject_class_fk FOREIGN KEY (school_id, class_id) REFERENCES school_class (school_id, id),
    CONSTRAINT class_subject_subject_fk FOREIGN KEY (school_id, subject_id) REFERENCES subject (school_id, id),
    CONSTRAINT class_subject_passing CHECK (passing_marks IS NULL OR (passing_marks >= 0 AND passing_marks <= max_marks))
);

-- ---------------------------------------------------------------------
-- Row-level security on every new tenant table
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['role', 'role_permission', 'user_role', 'account_status_change', 'password_token',
                             'stored_file', 'school_profile', 'academic_year', 'working_day', 'calendar_day_off',
                             'setting_value', 'school_class', 'section', 'subject', 'class_subject']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('CREATE POLICY tenant_isolation ON %I
                            USING (school_id = app_current_school() OR app_all_schools())
                            WITH CHECK (school_id = app_current_school() OR app_all_schools())', t);
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------
-- Grants. History tables are insert-only for the app.
-- ---------------------------------------------------------------------
GRANT SELECT, INSERT ON platform_login_event, account_status_change, stored_file, setting_value TO sms_app;
GRANT SELECT, INSERT, UPDATE ON password_token, school_profile, academic_year TO sms_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON role, role_permission, user_role, working_day, calendar_day_off,
    school_class, section, subject, class_subject TO sms_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO sms_app;
